/** A random display name, not a unique account identifier. */
export function generateDisplayName(): string {
  return [
    nameWords.sizes,
    nameWords.personalities,
    nameWords.colors,
    nameWords.animals,
  ]
    .map((words) => words[Math.floor(Math.random() * words.length)])
    .join("");
}
